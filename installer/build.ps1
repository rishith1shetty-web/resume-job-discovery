<#
.SYNOPSIS
    Build the Windows installer for Rising Path Recruiters Job Finding Automation.

.DESCRIPTION
    Produces dist\RisingPathRecruitersJobFindingAutomationSetup.exe from a clean checkout, in five
    stages:

        1. Build the React interface to static files.
        2. Freeze the launcher with PyInstaller (one directory - fast start).
        3. Freeze the provisioning tool (one file - the installer has to run
           it before anything is installed, so it cannot depend on a folder).
        4. Stage everything the installer packages.
        5. Compile the Inno Setup script.

    Every stage fails loudly. A build that half-succeeds would produce an
    installer that looks complete and is not, which is worse than no installer.

.PARAMETER SkipFrontend
    Reuse an existing frontend\dist. For iterating on the installer only.

.PARAMETER Version
    Version stamped into the installer. Must match the .iss default unless you
    are deliberately overriding it.

.EXAMPLE
    .\installer\build.ps1
#>
[CmdletBinding()]
param(
    [switch]$SkipFrontend,
    [string]$Version = '1.0.0'
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$RepoRoot     = Split-Path -Parent $PSScriptRoot
$InstallerDir = Join-Path $RepoRoot 'installer'
$StagingDir   = Join-Path $InstallerDir 'staging'
$DistDir      = Join-Path $RepoRoot 'dist'
$BuildDir     = Join-Path $RepoRoot 'build'
$FrontendDir  = Join-Path $RepoRoot 'frontend'
$Python       = Join-Path $RepoRoot '.venv\Scripts\python.exe'

function Write-Stage([string]$Text) {
    Write-Host ''
    Write-Host "=== $Text " -NoNewline
    Write-Host ('=' * [Math]::Max(0, 68 - $Text.Length))
}

function Assert-LastExit([string]$What) {
    if ($LASTEXITCODE -ne 0) { throw "$What failed with exit code $LASTEXITCODE." }
}

if (-not (Test-Path $Python)) {
    throw "The virtual environment is missing ($Python). Create it and install the project first."
}

# --- Locate the Inno Setup compiler ----------------------------------------
$IsccCandidates = @(
    'C:\Program Files (x86)\Inno Setup 6\ISCC.exe',
    'C:\Program Files\Inno Setup 6\ISCC.exe'
)
$Iscc = $IsccCandidates | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $Iscc) {
    throw "Inno Setup 6 was not found. Install it from https://jrsoftware.org/isdl.php"
}

Write-Host "Repository   $RepoRoot"
Write-Host "Python       $Python"
Write-Host "Inno Setup   $Iscc"
Write-Host "Version      $Version"

# --- 1. Frontend ------------------------------------------------------------
Write-Stage 'Building the interface'
if ($SkipFrontend -and (Test-Path (Join-Path $FrontendDir 'dist\index.html'))) {
    Write-Host 'Reusing the existing frontend\dist (-SkipFrontend).'
} else {
    Push-Location $FrontendDir
    try {
        if (-not (Test-Path 'node_modules')) {
            Write-Host 'Installing npm dependencies...'
            npm install --no-audit --no-fund
            Assert-LastExit 'npm install'
        }
        # Same origin in production: the API serves these files itself, so the
        # client must use a relative base URL rather than a hard-coded host.
        Set-Content -Path '.env.production' -Encoding utf8 -Value @'
# Generated by installer\build.ps1. The packaged application serves the
# interface and the API from one origin, so the base URL is relative.
VITE_API_BASE_URL=/api/v1
'@
        npm run build
        Assert-LastExit 'npm run build'
    } finally {
        Pop-Location
    }
}

$FrontendDist = Join-Path $FrontendDir 'dist'
if (-not (Test-Path (Join-Path $FrontendDist 'index.html'))) {
    throw "The interface did not build: $FrontendDist\index.html is missing."
}

# --- 2 & 3. Freeze ----------------------------------------------------------
Write-Stage 'Freezing the application'

foreach ($stale in @($BuildDir, $StagingDir)) {
    if (Test-Path $stale) { Remove-Item -Recurse -Force $stale }
}
New-Item -ItemType Directory -Force -Path $DistDir | Out-Null

Push-Location $RepoRoot
try {
    & $Python -m PyInstaller --noconfirm --clean `
        (Join-Path $InstallerDir 'launcher.spec')
    Assert-LastExit 'PyInstaller (launcher)'

    & $Python -m PyInstaller --noconfirm --clean `
        (Join-Path $InstallerDir 'provision.spec')
    Assert-LastExit 'PyInstaller (provisioning tool)'
} finally {
    Pop-Location
}

$LauncherOut  = Join-Path $DistDir 'RisingPathRecruitersJobFindingAutomation'
$ProvisionOut = Join-Path $DistDir 'provision-database.exe'
foreach ($required in @($LauncherOut, $ProvisionOut)) {
    if (-not (Test-Path $required)) { throw "PyInstaller did not produce $required." }
}

# --- 4. Stage ---------------------------------------------------------------
Write-Stage 'Staging installer inputs'

$StagingApp  = Join-Path $StagingDir 'app'
$StagingDocs = Join-Path $StagingDir 'docs'
New-Item -ItemType Directory -Force -Path $StagingApp, $StagingDocs | Out-Null

Copy-Item -Recurse -Force (Join-Path $LauncherOut '*') $StagingApp
Copy-Item -Force $ProvisionOut $StagingApp

# Shipped inside the installation, for whoever supports the machine later.
$MaintainerDoc = Join-Path $RepoRoot 'docs\WINDOWS_INSTALLER.md'
if (Test-Path $MaintainerDoc) { Copy-Item -Force $MaintainerDoc $StagingDocs }

# The end-user guides travel BESIDE the installer, not inside it: someone who
# cannot get PostgreSQL installed cannot read a file that only exists after a
# successful install.
$ReleaseDocs = Join-Path $InstallerDir 'release-docs'
Get-ChildItem -File $ReleaseDocs | Copy-Item -Destination $StagingDocs -Force

if (-not (Get-ChildItem -File $StagingDocs)) {
    throw "No documentation was staged."
}

$LauncherExe = Join-Path $StagingApp 'RisingPathRecruitersJobFindingAutomation.exe'
if (-not (Test-Path $LauncherExe)) {
    throw "The staged application is missing its executable."
}
if (-not (Test-Path (Join-Path $StagingApp '_internal\frontend_dist\index.html'))) {
    throw "The staged application is missing the built interface."
}
if (-not (Test-Path (Join-Path $StagingApp '_internal\migrations'))) {
    throw "The staged application is missing the database migrations."
}

$StagedSize = (Get-ChildItem -Recurse $StagingDir | Measure-Object -Property Length -Sum).Sum
Write-Host ("Staged {0:N1} MB" -f ($StagedSize / 1MB))

# --- 5. Compile -------------------------------------------------------------
Write-Stage 'Compiling the installer'

& $Iscc "/DAppVersion=$Version" (Join-Path $InstallerDir 'ResumeJobDiscovery.iss')
Assert-LastExit 'Inno Setup'

$Setup = Join-Path $DistDir 'RisingPathRecruitersJobFindingAutomationSetup.exe'
if (-not (Test-Path $Setup)) { throw "Inno Setup did not produce $Setup." }

$Hash = (Get-FileHash $Setup -Algorithm SHA256).Hash
$SetupSize = (Get-Item $Setup).Length

# The release folder is what gets handed over: the installer, its checksum and
# the two guides the user needs BEFORE the application exists on their machine.
$ReleaseDir = Join-Path $DistDir "RisingPathRecruitersJobFindingAutomation-$Version"
if (Test-Path $ReleaseDir) { Remove-Item -Recurse -Force $ReleaseDir }
New-Item -ItemType Directory -Force -Path $ReleaseDir | Out-Null

Copy-Item -Force $Setup $ReleaseDir
Get-ChildItem -File (Join-Path $InstallerDir 'release-docs') |
    Copy-Item -Destination $ReleaseDir -Force

Set-Content -Path (Join-Path $ReleaseDir 'SHA256.txt') -Encoding utf8 -Value @"
RisingPathRecruitersJobFindingAutomationSetup.exe
$Hash

Verify before running:
    Get-FileHash .\RisingPathRecruitersJobFindingAutomationSetup.exe -Algorithm SHA256
"@

Write-Stage 'Done'
Write-Host ("Installer   {0}" -f $Setup)
Write-Host ("Size        {0:N1} MB" -f ($SetupSize / 1MB))
Write-Host ("SHA256      {0}" -f $Hash)
Write-Host ("Release     {0}" -f $ReleaseDir)
Get-ChildItem $ReleaseDir | ForEach-Object {
    Write-Host ("              {0,-46} {1,10:N0} bytes" -f $_.Name, $_.Length)
}
