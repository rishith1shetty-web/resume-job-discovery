"""Where this application reads and writes, in development and once installed.

Two very different layouts have to work from the same code:

  Development   everything lives beside the source tree, which is convenient
                and disposable.

  Installed     the program lives under Program Files, which is read-only for
                the user running it, so nothing may be written there. Data
                belongs to the Windows account instead, under LOCALAPPDATA.

Getting this wrong is not a cosmetic problem. A packaged application that
writes beside its executable either fails outright on a standard account or,
worse, succeeds for an administrator and silently loses that data for everyone
else. So the decision is made once, here, and every other module asks rather
than assembles its own path.

The mode is deliberately explicit rather than guessed. ``sys.frozen`` alone is
not enough: the build pipeline freezes the provisioning tool too, and that runs
during installation before any of this exists.
"""

from __future__ import annotations

import os
import sys
from functools import lru_cache
from pathlib import Path

#: Set by the installer and the launcher. Its presence means "installed", and
#: its value is the data root. An explicit variable keeps the behaviour
#: testable and lets support redirect a broken installation without a rebuild.
DATA_DIR_ENV = "JOBFINDER_DATA_DIR"

#: Folder name under %LOCALAPPDATA% when the variable is not set.
APP_DATA_FOLDER = "RisingPathRecruitersJobFindingAutomation"

#: The source checkout. Correct in development; meaningless once frozen, which
#: is exactly why installed mode never derives a writable path from it.
PROJECT_ROOT = Path(__file__).resolve().parents[2]


def is_frozen() -> bool:
    """Whether this is running from a PyInstaller bundle."""
    return bool(getattr(sys, "frozen", False))


def bundle_root() -> Path:
    """Read-only directory holding bundled resources.

    Under PyInstaller this is the unpacked bundle (``sys._MEIPASS``); in
    development it is the source tree. Templates, migrations and the built
    frontend are read from here — never written to.
    """
    if is_frozen():
        return Path(getattr(sys, "_MEIPASS", Path(sys.executable).parent))
    return PROJECT_ROOT


def install_root() -> Path:
    """Directory containing the installed executable, or the source tree."""
    if is_frozen():
        return Path(sys.executable).resolve().parent
    return PROJECT_ROOT


@lru_cache(maxsize=1)
def data_dir() -> Path:
    """Writable root for everything this installation owns.

    Resolution order:

    1. ``JOBFINDER_DATA_DIR`` when set — the installer, the launcher and the
       tests all use this.
    2. ``%LOCALAPPDATA%\\RisingPathRecruitersJobFindingAutomation`` when frozen.
    3. The source tree in development.

    Per user, not per machine: the database credential is protected with DPAPI
    under the user's own key, so the data that credential unlocks belongs
    beside it rather than in a shared location another account could read but
    not decrypt.
    """
    override = os.environ.get(DATA_DIR_ENV)
    if override:
        return Path(override).expanduser().resolve()

    if is_frozen():
        local = os.environ.get("LOCALAPPDATA")
        if local:
            return Path(local) / APP_DATA_FOLDER
        # LOCALAPPDATA is always set on Windows; this only guards a service
        # account with a stripped environment.
        return Path.home() / "AppData" / "Local" / APP_DATA_FOLDER

    return PROJECT_ROOT


def config_dir() -> Path:
    return data_dir() / "config"


def storage_dir() -> Path:
    """Uploaded resumes. In development this stays the existing ``storage/``."""
    return data_dir() / "storage"


def logs_dir() -> Path:
    return data_dir() / "logs"


def env_file() -> Path:
    """The generated configuration file.

    In development this is the checked-out ``.env`` and is never written by
    the application. Once installed it is generated by the installer.
    """
    return config_dir() / "app.env" if is_installed() else PROJECT_ROOT / ".env"


def credential_file() -> Path:
    """DPAPI-protected database credential. Only ever readable by its owner."""
    return config_dir() / "database_credential.dat"


def frontend_dist() -> Path:
    """The built single-page application served by the API in production.

    In a frozen build this is the bundled copy. In development it is Vite's
    own output directory — deliberately, so that running `npm run build` once
    makes a source checkout exercise the *same* serving path the packaged
    application uses. Pointing this somewhere that never exists in development
    means the static-serving code is only ever executed inside the installer,
    which is precisely where a mistake in it is most expensive to find.
    """
    if is_frozen():
        return bundle_root() / "frontend_dist"
    return PROJECT_ROOT / "frontend" / "dist"


def is_installed() -> bool:
    """Whether this process is running as an installed application."""
    return bool(os.environ.get(DATA_DIR_ENV)) or is_frozen()


def ensure_data_tree() -> Path:
    """Create the writable directories this installation needs.

    Safe to call repeatedly; called by both the installer and every launch, so
    a folder a user deleted by hand comes back rather than crashing the app.
    """
    root = data_dir()
    for path in (root, config_dir(), storage_dir(), logs_dir()):
        path.mkdir(parents=True, exist_ok=True)
    return root


