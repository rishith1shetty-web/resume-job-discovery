"""Taxonomy lookup API.

Builds indexes over the domain, role and skill data and validates them at
import time. A malformed taxonomy fails fast on startup rather than producing
silently wrong role detection later.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from functools import lru_cache

from app.analysis.taxonomy.roles_data import DOMAIN_ENTRIES, ROLE_ENTRIES
from app.analysis.taxonomy.skills_data import SKILL_ENTRIES
from app.analysis.text import normalize_title, normalize_token, word_boundary_pattern
from app.core.constants import SkillKind

# Prefixes that express seniority rather than a different job. Variations are
# generated by combining these with a role's canonical title, so they must not
# appear inside the stored variation data.
#
# Deliberately narrow. "Staff", "Associate" and "Head of" are excluded because
# they are part of established distinct titles - "Staff Accountant",
# "Associate Product Manager", "Audit Associate" - rather than seniority
# modifiers of a base title.
SENIORITY_PREFIXES: tuple[str, ...] = (
    "junior",
    "jr",
    "senior",
    "sr",
    "lead",
    "principal",
    "entry level",
    "entry-level",
)


@dataclass(frozen=True, slots=True)
class DomainSpec:
    key: str
    display_name: str
    keywords: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class RoleSpec:
    key: str
    canonical_title: str
    domain_key: str
    aliases: tuple[str, ...]
    variations: tuple[str, ...]
    core_skills: tuple[str, ...]

    @property
    def match_terms(self) -> tuple[str, ...]:
        """Normalised forms that identify this role in a resume."""
        return (normalize_title(self.canonical_title), *self.aliases)


@dataclass(frozen=True, slots=True)
class SkillSpec:
    key: str
    display: str
    kind: SkillKind
    aliases: tuple[str, ...] = field(default=())
    domains: tuple[str, ...] = field(default=())

    @property
    def match_terms(self) -> tuple[str, ...]:
        return (self.key, *self.aliases)


def _build_domains() -> dict[str, DomainSpec]:
    return {
        key: DomainSpec(key=key, display_name=name, keywords=keywords)
        for key, name, keywords in DOMAIN_ENTRIES
    }


def _build_roles() -> dict[str, RoleSpec]:
    return {
        key: RoleSpec(
            key=key,
            canonical_title=title,
            domain_key=domain,
            aliases=tuple(normalize_title(alias) for alias in aliases),
            variations=variations,
            core_skills=core_skills,
        )
        for key, title, domain, aliases, variations, core_skills in ROLE_ENTRIES
    }


def _build_skills() -> dict[str, SkillSpec]:
    return {
        key: SkillSpec(
            key=key,
            display=display,
            kind=kind,
            aliases=tuple(normalize_token(alias) for alias in aliases),
            domains=domains,
        )
        for key, display, kind, aliases, domains in SKILL_ENTRIES
    }


DOMAINS: dict[str, DomainSpec] = _build_domains()
ROLES: dict[str, RoleSpec] = _build_roles()
SKILLS: dict[str, SkillSpec] = _build_skills()


def _validate() -> None:
    """Fail fast on taxonomy defects."""
    seniority_re = re.compile(
        rf"^({'|'.join(re.escape(prefix) for prefix in SENIORITY_PREFIXES)})\b"
    )

    for role in ROLES.values():
        if role.domain_key not in DOMAINS:
            raise ValueError(
                f"Role {role.key!r} references unknown domain {role.domain_key!r}."
            )
        for skill_key in role.core_skills:
            if skill_key not in SKILLS:
                raise ValueError(
                    f"Role {role.key!r} references unknown skill {skill_key!r}."
                )
        normalized_variations = {normalize_title(v) for v in role.variations}
        if normalize_title(role.canonical_title) not in normalized_variations:
            raise ValueError(
                f"Role {role.key!r} must list its canonical title among variations."
            )
        for variation in role.variations:
            # Seniority forms are generated at runtime; storing them here would
            # produce duplicates and blur the same-role guarantee.
            if seniority_re.match(normalize_title(variation)):
                raise ValueError(
                    f"Role {role.key!r} variation {variation!r} contains a "
                    "seniority prefix; those are generated, not stored."
                )

    for skill in SKILLS.values():
        for domain_key in skill.domains:
            if domain_key not in DOMAINS:
                raise ValueError(
                    f"Skill {skill.key!r} references unknown domain {domain_key!r}."
                )

    # An alias shared by two roles would make detection order-dependent.
    seen: dict[str, str] = {}
    for role in ROLES.values():
        for term in role.match_terms:
            if term in seen and seen[term] != role.key:
                raise ValueError(
                    f"Role term {term!r} is claimed by both {seen[term]!r} "
                    f"and {role.key!r}."
                )
            seen[term] = role.key


_validate()


# --- Indexes ---------------------------------------------------------------

_ROLE_TERM_TO_KEY: dict[str, str] = {
    term: role.key for role in ROLES.values() for term in role.match_terms
}
_SKILL_TERM_TO_KEY: dict[str, str] = {
    term: skill.key for skill in SKILLS.values() for term in skill.match_terms
}
_DOMAIN_KEYWORD_TO_KEY: dict[str, str] = {
    normalize_token(keyword): domain.key
    for domain in DOMAINS.values()
    for keyword in domain.keywords
}


@lru_cache(maxsize=1)
def role_pattern() -> re.Pattern[str]:
    """Regex matching any known role title or alias."""
    return word_boundary_pattern(list(_ROLE_TERM_TO_KEY))


@lru_cache(maxsize=1)
def skill_pattern() -> re.Pattern[str]:
    """Regex matching any known skill, technology or tool."""
    return word_boundary_pattern(list(_SKILL_TERM_TO_KEY))


@lru_cache(maxsize=1)
def domain_keyword_pattern() -> re.Pattern[str]:
    """Regex matching any domain-signalling phrase."""
    return word_boundary_pattern(list(_DOMAIN_KEYWORD_TO_KEY))


# --- Accessors -------------------------------------------------------------


def get_domain(key: str) -> DomainSpec | None:
    return DOMAINS.get(key)


def get_role(key: str) -> RoleSpec | None:
    return ROLES.get(key)


def get_skill(key: str) -> SkillSpec | None:
    return SKILLS.get(key)


def role_key_for_term(term: str) -> str | None:
    """Resolve a matched surface form to its role key."""
    return _ROLE_TERM_TO_KEY.get(normalize_title(term))


def skill_key_for_term(term: str) -> str | None:
    """Resolve a matched surface form to its skill key."""
    return _SKILL_TERM_TO_KEY.get(normalize_token(term))


def domain_key_for_keyword(keyword: str) -> str | None:
    return _DOMAIN_KEYWORD_TO_KEY.get(normalize_token(keyword))


def roles_for_domain(domain_key: str) -> tuple[RoleSpec, ...]:
    return tuple(role for role in ROLES.values() if role.domain_key == domain_key)


def skills_for_domain(domain_key: str) -> tuple[SkillSpec, ...]:
    return tuple(skill for skill in SKILLS.values() if domain_key in skill.domains)


